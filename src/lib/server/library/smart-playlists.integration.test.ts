import { describe, it, expect, beforeEach } from 'vitest';
import { env } from 'cloudflare:test';
import { eq } from 'drizzle-orm';
import { getDb } from '../db';
import {
	users,
	songs,
	playlists,
	playlistSongs,
	userSongs,
	importJobs,
	songEmbeddings
} from '../db/schema';
import {
	generateSmartPlaylistsForUser,
	generateSmartPlaylistsForAllUsers,
	RECENTLY_PLAYED_NAME,
	ON_REPEAT_NAME,
	FORGOTTEN_FAVORITES_NAME,
	THIS_WEEKS_VIBE_NAME,
	DEEP_CUTS_NAME,
	SOUND_CLUSTERS_NAME
} from './smart-playlists';
import { createPlaylist, addSongToPlaylist, ensureDefaultPlaylist } from './playlists';
import { encodeVector } from '../embedding/vector-codec';

const db = getDb(env);

async function seedUser(id: string) {
	await db
		.insert(users)
		.values({ id, username: `user-${id}`, passwordHash: 'x' })
		.onConflictDoNothing();
}

async function seedSong(videoId: string, overrides: Partial<typeof songs.$inferInsert> = {}) {
	await db
		.insert(songs)
		.values({
			videoId,
			sourcePlatform: 'youtube',
			sourceUrl: `https://youtube.com/watch?v=${videoId}`,
			title: `Song ${videoId}`,
			audioKey: `audio/${videoId}.webm`,
			codec: 'opus',
			container: 'webm',
			fileSizeBytes: 1000,
			...overrides
		})
		.onConflictDoNothing();
}

/** Seeds a full library of `count` songs for `userId`, added to their default playlist. Each gets a distinct artist unless overridden per-index via `artistOf`. */
async function seedLibrary(
	userId: string,
	count: number,
	artistOf: (i: number) => string | null = (i) => `Artist ${i}`
) {
	const { id: defaultPlaylistId } = await ensureDefaultPlaylist(db, userId);
	for (let i = 0; i < count; i++) {
		const videoId = `v${i}`;
		await seedSong(videoId, { artist: artistOf(i) });
		await addSongToPlaylist(db, defaultPlaylistId, userId, videoId);
	}
}

async function seedPlay(
	userId: string,
	videoId: string,
	playCount: number,
	lastPlayedAt: string | null
) {
	await db
		.insert(userSongs)
		.values({ userId, videoId, playCount, lastPlayedAt })
		.onConflictDoUpdate({
			target: [userSongs.userId, userSongs.videoId],
			set: { playCount, lastPlayedAt }
		});
}

async function seedEmbedding(videoId: string, vector: number[]) {
	await db
		.insert(songEmbeddings)
		.values({ videoId, vector: Buffer.from(encodeVector(vector)) })
		.onConflictDoNothing();
}

function daysAgo(days: number): string {
	return new Date(Date.now() - days * 24 * 60 * 60 * 1000).toISOString();
}

async function autoGeneratedPlaylists(userId: string) {
	return db.query.playlists.findMany({
		where: (t, { and, eq }) => and(eq(t.userId, userId), eq(t.kind, 'auto_generated'))
	});
}

async function playlistVideoIds(playlistId: string): Promise<Set<string>> {
	const rows = await db.query.playlistSongs.findMany({
		where: eq(playlistSongs.playlistId, playlistId)
	});
	return new Set(rows.map((r) => r.videoId));
}

async function findGeneratedPlaylist(userId: string, name: string) {
	return db.query.playlists.findFirst({
		where: (t, { and, eq }) =>
			and(eq(t.userId, userId), eq(t.kind, 'auto_generated'), eq(t.name, name))
	});
}

beforeEach(async () => {
	await db.update(users).set({ defaultPlaylistId: null });
	await db.delete(importJobs);
	await db.delete(userSongs);
	await db.delete(songEmbeddings);
	await db.delete(playlistSongs);
	await db.delete(playlists);
	await db.delete(songs);
	await db.delete(users);
});

describe('generateSmartPlaylistsForUser', () => {
	it('generates no play-history/embedding playlists for a library below the minimum size', async () => {
		await seedUser('u1');
		await seedLibrary('u1', 29, () => null);

		await generateSmartPlaylistsForUser(db, 'u1');

		const generated = await autoGeneratedPlaylists('u1');
		expect(generated).toEqual([]);
	});

	it('still generates artist groupings for a library below the minimum size', async () => {
		await seedUser('u1');
		// Below the 30-song recommendation floor, but "Radiohead" still has
		// enough songs to qualify as its own grouping — artist groupings
		// aren't gated by MIN_LIBRARY_SIZE_FOR_RECOMMENDATIONS.
		await seedLibrary('u1', 10, (i) => (i < 3 ? 'Radiohead' : null));

		await generateSmartPlaylistsForUser(db, 'u1');

		const generated = await autoGeneratedPlaylists('u1');
		expect(generated.map((p) => p.name)).toEqual(['Radiohead']);
	});

	it('generates the 3 play-history playlists once the library meets the minimum size', async () => {
		await seedUser('u1');
		await seedLibrary('u1', 30, () => null);
		await seedPlay('u1', 'v0', 5, daysAgo(1)); // feeds Recently Played + On Repeat
		await seedPlay('u1', 'v1', 20, daysAgo(60)); // feeds Forgotten Favorites + On Repeat

		await generateSmartPlaylistsForUser(db, 'u1');

		const names = (await autoGeneratedPlaylists('u1')).map((p) => p.name);
		expect(names).toContain(RECENTLY_PLAYED_NAME);
		expect(names).toContain(ON_REPEAT_NAME);
		expect(names).toContain(FORGOTTEN_FAVORITES_NAME);
	});

	describe('Recently Played', () => {
		it('includes only songs played within the last 7 days, most recent first', async () => {
			await seedUser('u1');
			await seedLibrary('u1', 30, () => null);
			await seedPlay('u1', 'v0', 5, daysAgo(1));
			await seedPlay('u1', 'v1', 5, daysAgo(3));
			await seedPlay('u1', 'v2', 5, daysAgo(8)); // outside the 7-day window

			await generateSmartPlaylistsForUser(db, 'u1');

			const playlist = await findGeneratedPlaylist('u1', RECENTLY_PLAYED_NAME);
			const rows = await db.query.playlistSongs.findMany({
				where: eq(playlistSongs.playlistId, playlist!.id),
				orderBy: (t, { asc }) => asc(t.position)
			});
			expect(rows.map((r) => r.videoId)).toEqual(['v0', 'v1']);
		});
	});

	describe('On Repeat', () => {
		it('ranks by playCount alone, regardless of recency, excluding unplayed songs', async () => {
			await seedUser('u1');
			await seedLibrary('u1', 30, () => null);
			await seedPlay('u1', 'v0', 100, daysAgo(200)); // old but heavily played
			await seedPlay('u1', 'v1', 5, daysAgo(1)); // recent but barely played

			await generateSmartPlaylistsForUser(db, 'u1');

			const playlist = await findGeneratedPlaylist('u1', ON_REPEAT_NAME);
			const rows = await db.query.playlistSongs.findMany({
				where: eq(playlistSongs.playlistId, playlist!.id),
				orderBy: (t, { asc }) => asc(t.position)
			});
			expect(rows[0].videoId).toBe('v0');
			expect(rows.map((r) => r.videoId)).not.toContain('v29'); // never played
		});
	});

	describe('Forgotten Favorites', () => {
		it('includes only songs unplayed for 30+ days with above-median play counts', async () => {
			await seedUser('u1');
			await seedLibrary('u1', 30, () => null);
			// v0: played often, long ago -> forgotten favorite
			await seedPlay('u1', 'v0', 20, daysAgo(60));
			// v1: played once, long ago -> below median, excluded
			await seedPlay('u1', 'v1', 1, daysAgo(60));
			// v2: played often, but recently -> excluded (not forgotten)
			await seedPlay('u1', 'v2', 20, daysAgo(1));

			await generateSmartPlaylistsForUser(db, 'u1');

			const playlist = await findGeneratedPlaylist('u1', FORGOTTEN_FAVORITES_NAME);
			const ids = await playlistVideoIds(playlist!.id);
			expect(ids.has('v0')).toBe(true);
			expect(ids.has('v1')).toBe(false);
			expect(ids.has('v2')).toBe(false);
		});
	});

	describe("This Week's Vibe / Deep Cuts", () => {
		it('ranks the library by similarity to the recent-plays-weighted vector', async () => {
			await seedUser('u1');
			await seedLibrary('u1', 30, () => null);
			await seedPlay('u1', 'v0', 10, daysAgo(1)); // recent play, seeds the vibe vector
			await seedEmbedding('v0', [1, 0]);
			await seedEmbedding('v1', [0.9, 0.1]); // close to v0's vibe
			await seedEmbedding('v2', [-1, 0]); // opposite of v0's vibe
			for (let i = 3; i < 30; i++) await seedEmbedding(`v${i}`, [0, 1]); // neutral filler, distinct from both ends

			await generateSmartPlaylistsForUser(db, 'u1');

			const vibe = await findGeneratedPlaylist('u1', THIS_WEEKS_VIBE_NAME);
			const vibeRows = await db.query.playlistSongs.findMany({
				where: eq(playlistSongs.playlistId, vibe!.id),
				orderBy: (t, { asc }) => asc(t.position)
			});
			expect(vibeRows[0].videoId).toBe('v0');
			expect(vibeRows.map((r) => r.videoId).slice(0, 2)).toContain('v1');

			const deepCuts = await findGeneratedPlaylist('u1', DEEP_CUTS_NAME);
			const deepCutsRows = await db.query.playlistSongs.findMany({
				where: eq(playlistSongs.playlistId, deepCuts!.id),
				orderBy: (t, { asc }) => asc(t.position)
			});
			expect(deepCutsRows[0].videoId).toBe('v2');
		});

		it('generates neither playlist when nothing was played in the last 7 days', async () => {
			await seedUser('u1');
			await seedLibrary('u1', 30, () => null);
			for (let i = 0; i < 30; i++) await seedEmbedding(`v${i}`, [1, 0]);
			// No plays at all -> no vibe vector can be computed.

			await generateSmartPlaylistsForUser(db, 'u1');

			expect(await findGeneratedPlaylist('u1', THIS_WEEKS_VIBE_NAME)).toBeUndefined();
			expect(await findGeneratedPlaylist('u1', DEEP_CUTS_NAME)).toBeUndefined();
		});

		it('generates neither playlist when no embeddings exist yet', async () => {
			await seedUser('u1');
			await seedLibrary('u1', 30, () => null);
			await seedPlay('u1', 'v0', 10, daysAgo(1));
			// No embeddings seeded at all.

			await generateSmartPlaylistsForUser(db, 'u1');

			expect(await findGeneratedPlaylist('u1', THIS_WEEKS_VIBE_NAME)).toBeUndefined();
			expect(await findGeneratedPlaylist('u1', DEEP_CUTS_NAME)).toBeUndefined();
		});
	});

	describe('Sound Clusters', () => {
		it('generates a single-cluster playlist for a library with embeddings', async () => {
			await seedUser('u1');
			await seedLibrary('u1', 30, () => null);
			// Two tight, well-separated groups of vectors -> k-means should
			// recover roughly this structure regardless of which one it picks
			// as "largest".
			for (let i = 0; i < 15; i++) await seedEmbedding(`v${i}`, [1, 0]);
			for (let i = 15; i < 30; i++) await seedEmbedding(`v${i}`, [0, 1]);

			await generateSmartPlaylistsForUser(db, 'u1');

			const playlist = await findGeneratedPlaylist('u1', SOUND_CLUSTERS_NAME);
			expect(playlist).toBeDefined();
			const ids = await playlistVideoIds(playlist!.id);
			expect(ids.size).toBeGreaterThan(0);
			// Every member should come from the same one of the two seeded
			// groups — a correct single-cluster pick shouldn't straddle both.
			const fromFirstGroup = [...ids].filter((id) => Number(id.slice(1)) < 15).length;
			const fromSecondGroup = ids.size - fromFirstGroup;
			expect(fromFirstGroup === 0 || fromSecondGroup === 0).toBe(true);
		});

		it('is skipped when no embeddings exist', async () => {
			await seedUser('u1');
			await seedLibrary('u1', 30, () => null);

			await generateSmartPlaylistsForUser(db, 'u1');

			expect(await findGeneratedPlaylist('u1', SOUND_CLUSTERS_NAME)).toBeUndefined();
		});
	});

	it('writes a playlist larger than the D1 bound-parameter insert-chunk size', async () => {
		await seedUser('u1');
		await seedLibrary('u1', 150, () => null);
		for (let i = 0; i < 150; i++) await seedPlay('u1', `v${i}`, i + 1, daysAgo(1));

		await generateSmartPlaylistsForUser(db, 'u1');

		const playlist = await findGeneratedPlaylist('u1', ON_REPEAT_NAME);
		const ids = await playlistVideoIds(playlist!.id);
		expect(ids.size).toBe(100); // MAX_SONGS_PER_SMART_PLAYLIST cap
	});

	it('groups by artist, excluding groups below the minimum song count', async () => {
		await seedUser('u1');
		// 30 songs total: 3 for "Radiohead" (qualifies), 1 for "Solo Artist"
		// (below MIN_SONGS_PER_ARTIST), remaining 26 with no shared artist.
		await seedLibrary('u1', 30, (i) => {
			if (i < 3) return 'Radiohead';
			if (i === 3) return 'Solo Artist';
			return null;
		});

		await generateSmartPlaylistsForUser(db, 'u1');

		const generated = await autoGeneratedPlaylists('u1');
		const names = generated.map((p) => p.name);
		expect(names).toContain('Radiohead');
		expect(names).not.toContain('Solo Artist');
	});

	it('excludes songs with no artist from any artist grouping', async () => {
		await seedUser('u1');
		await seedLibrary('u1', 30, () => null);

		await generateSmartPlaylistsForUser(db, 'u1');

		const generated = await autoGeneratedPlaylists('u1');
		expect(generated.some((p) => p.name === 'null')).toBe(false);
	});

	it('replaces previously generated auto_generated playlists on a second run rather than duplicating them', async () => {
		await seedUser('u1');
		await seedLibrary('u1', 30, () => null);
		await seedPlay('u1', 'v0', 5, daysAgo(1));

		await generateSmartPlaylistsForUser(db, 'u1');
		const firstRun = await autoGeneratedPlaylists('u1');
		expect(firstRun.length).toBeGreaterThan(0);

		await generateSmartPlaylistsForUser(db, 'u1');
		const secondRun = await autoGeneratedPlaylists('u1');

		expect(secondRun.length).toBe(firstRun.length);
		expect(secondRun.map((p) => p.id).sort()).not.toEqual(firstRun.map((p) => p.id).sort());
	});

	it("never touches existing kind='user' playlists", async () => {
		await seedUser('u1');
		await seedLibrary('u1', 30, () => null);
		const { id: customPlaylistId } = await createPlaylist(db, { userId: 'u1', name: 'My Mix' });

		await generateSmartPlaylistsForUser(db, 'u1');

		const survived = await db.query.playlists.findFirst({
			where: eq(playlists.id, customPlaylistId)
		});
		expect(survived).toBeDefined();
		expect(survived?.kind).toBe('user');
	});
});

describe('generateSmartPlaylistsForAllUsers', () => {
	it('generates for every user and reports how many were processed', async () => {
		await seedUser('u1');
		await seedUser('u2');
		await seedLibrary('u1', 30, () => null);
		await seedLibrary('u2', 5, () => null); // below minimum, generates nothing (no shared artists either)

		const result = await generateSmartPlaylistsForAllUsers(db);

		expect(result.processedUsers).toBe(2);
		expect(await autoGeneratedPlaylists('u2')).toEqual([]);
	});
});
