import { describe, it, expect, beforeEach } from 'vitest';
import { env } from 'cloudflare:test';
import { eq } from 'drizzle-orm';
import { getDb } from '../db';
import { users, songs, playlists, playlistSongs, userSongs, importJobs } from '../db/schema';
import { generateSmartPlaylistsForUser, generateSmartPlaylistsForAllUsers } from './smart-playlists';
import { createPlaylist, addSongToPlaylist, ensureDefaultPlaylist } from './playlists';

const db = getDb(env.DB);

async function seedUser(id: string) {
	await db.insert(users).values({ id, username: `user-${id}`, passwordHash: 'x' }).onConflictDoNothing();
}

async function seedSong(videoId: string, overrides: Partial<typeof songs.$inferInsert> = {}) {
	await db
		.insert(songs)
		.values({
			videoId,
			sourcePlatform: 'youtube',
			sourceUrl: `https://youtube.com/watch?v=${videoId}`,
			title: `Song ${videoId}`,
			audioKey: `audio/${videoId}.webm`,
			codec: 'opus',
			container: 'webm',
			fileSizeBytes: 1000,
			...overrides
		})
		.onConflictDoNothing();
}

/** Seeds a full library of `count` songs for `userId`, added to their default playlist. Each gets a distinct artist unless overridden per-index via `artistOf`. */
async function seedLibrary(userId: string, count: number, artistOf: (i: number) => string | null = (i) => `Artist ${i}`) {
	const { id: defaultPlaylistId } = await ensureDefaultPlaylist(db, userId);
	for (let i = 0; i < count; i++) {
		const videoId = `v${i}`;
		await seedSong(videoId, { artist: artistOf(i) });
		await addSongToPlaylist(db, defaultPlaylistId, userId, videoId);
	}
}

async function seedPlay(userId: string, videoId: string, playCount: number, lastPlayedAt: string | null) {
	await db
		.insert(userSongs)
		.values({ userId, videoId, playCount, lastPlayedAt })
		.onConflictDoUpdate({ target: [userSongs.userId, userSongs.videoId], set: { playCount, lastPlayedAt } });
}

async function autoGeneratedPlaylists(userId: string) {
	return db.query.playlists.findMany({
		where: (t, { and, eq }) => and(eq(t.userId, userId), eq(t.kind, 'auto_generated'))
	});
}

beforeEach(async () => {
	await db.update(users).set({ defaultPlaylistId: null });
	await db.delete(importJobs);
	await db.delete(userSongs);
	await db.delete(playlistSongs);
	await db.delete(playlists);
	await db.delete(songs);
	await db.delete(users);
});

describe('generateSmartPlaylistsForUser', () => {
	it('generates nothing for a library below the minimum size', async () => {
		await seedUser('u1');
		await seedLibrary('u1', 29);

		await generateSmartPlaylistsForUser(db, 'u1');

		expect(await autoGeneratedPlaylists('u1')).toEqual([]);
	});

	it('generates the three play-history playlists once the library meets the minimum size', async () => {
		await seedUser('u1');
		await seedLibrary('u1', 30, () => null); // no shared artists, isolate to just the 3 history playlists

		await generateSmartPlaylistsForUser(db, 'u1');

		const generated = await autoGeneratedPlaylists('u1');
		expect(generated.map((p) => p.name).sort()).toEqual(['Most Played', 'Never Played', 'Rediscover']);
		expect(generated.every((p) => p.kind === 'auto_generated')).toBe(true);
	});

	it('writes a playlist larger than the D1 bound-parameter insert-chunk size, uncapped', async () => {
		await seedUser('u1');
		// A library big enough that (a) a 20% slice exceeds the insert's
		// chunk size (30 rows) — regression test for the batch insert in
		// writeAutoGeneratedPlaylist — and (b) exceeds the old 50-song cap,
		// confirming the play-history playlists are no longer capped.
		await seedLibrary('u1', 400, () => null);

		await generateSmartPlaylistsForUser(db, 'u1');

		const mostPlayed = await db.query.playlists.findFirst({
			where: (t, { and, eq }) => and(eq(t.userId, 'u1'), eq(t.kind, 'auto_generated'), eq(t.name, 'Most Played'))
		});
		const songCount = await db.query.playlistSongs.findMany({
			where: eq(playlistSongs.playlistId, mostPlayed!.id)
		});
		expect(songCount.length).toBe(80); // 20% of 400, uncapped
	});

	it('groups by artist, excluding groups below the minimum song count', async () => {
		await seedUser('u1');
		// 30 songs total: 3 for "Radiohead" (qualifies), 1 for "Solo Artist"
		// (below MIN_SONGS_PER_ARTIST), remaining 26 with no shared artist.
		await seedLibrary('u1', 30, (i) => {
			if (i < 3) return 'Radiohead';
			if (i === 3) return 'Solo Artist';
			return null;
		});

		await generateSmartPlaylistsForUser(db, 'u1');

		const generated = await autoGeneratedPlaylists('u1');
		const names = generated.map((p) => p.name);
		expect(names).toContain('Radiohead');
		expect(names).not.toContain('Solo Artist');
	});

	it('excludes songs with no artist from any artist grouping', async () => {
		await seedUser('u1');
		await seedLibrary('u1', 30, () => null);

		await generateSmartPlaylistsForUser(db, 'u1');

		const generated = await autoGeneratedPlaylists('u1');
		expect(generated.some((p) => p.name === 'null')).toBe(false);
	});

	it('replaces previously generated auto_generated playlists on a second run rather than duplicating them', async () => {
		await seedUser('u1');
		await seedLibrary('u1', 30, () => null);

		await generateSmartPlaylistsForUser(db, 'u1');
		const firstRun = await autoGeneratedPlaylists('u1');

		await generateSmartPlaylistsForUser(db, 'u1');
		const secondRun = await autoGeneratedPlaylists('u1');

		expect(secondRun.length).toBe(firstRun.length);
		expect(secondRun.map((p) => p.id).sort()).not.toEqual(firstRun.map((p) => p.id).sort());
	});

	it('never touches existing kind=\'user\' playlists', async () => {
		await seedUser('u1');
		await seedLibrary('u1', 30, () => null);
		const { id: customPlaylistId } = await createPlaylist(db, { userId: 'u1', name: 'My Mix' });

		await generateSmartPlaylistsForUser(db, 'u1');

		const survived = await db.query.playlists.findFirst({ where: eq(playlists.id, customPlaylistId) });
		expect(survived).toBeDefined();
		expect(survived?.kind).toBe('user');
	});

	it('ranks "Most Played" above "Rediscover" above "Never Played" by play history', async () => {
		await seedUser('u1');
		await seedLibrary('u1', 30, () => null);
		const now = new Date().toISOString();
		// v0..v5 heavily played recently -> should land in "Most Played"
		for (let i = 0; i < 6; i++) await seedPlay('u1', `v${i}`, 50, now);
		// v24..v29 never played -> should land in "Never Played"

		await generateSmartPlaylistsForUser(db, 'u1');

		const mostPlayed = await db.query.playlists.findFirst({
			where: (t, { and, eq }) => and(eq(t.userId, 'u1'), eq(t.kind, 'auto_generated'), eq(t.name, 'Most Played'))
		});
		const mostPlayedSongs = await db.query.playlistSongs.findMany({
			where: eq(playlistSongs.playlistId, mostPlayed!.id)
		});
		const mostPlayedIds = new Set(mostPlayedSongs.map((s) => s.videoId));
		for (let i = 0; i < 6; i++) expect(mostPlayedIds.has(`v${i}`)).toBe(true);

		const neverPlayed = await db.query.playlists.findFirst({
			where: (t, { and, eq }) => and(eq(t.userId, 'u1'), eq(t.kind, 'auto_generated'), eq(t.name, 'Never Played'))
		});
		const neverPlayedSongs = await db.query.playlistSongs.findMany({
			where: eq(playlistSongs.playlistId, neverPlayed!.id)
		});
		const neverPlayedIds = new Set(neverPlayedSongs.map((s) => s.videoId));
		for (let i = 24; i < 30; i++) expect(neverPlayedIds.has(`v${i}`)).toBe(true);
	});
});

describe('generateSmartPlaylistsForAllUsers', () => {
	it('generates for every user and reports how many were processed', async () => {
		await seedUser('u1');
		await seedUser('u2');
		await seedLibrary('u1', 30, () => null);
		await seedLibrary('u2', 5, () => null); // below minimum, generates nothing

		const result = await generateSmartPlaylistsForAllUsers(db);

		expect(result.processedUsers).toBe(2);
		expect((await autoGeneratedPlaylists('u1')).length).toBeGreaterThan(0);
		expect(await autoGeneratedPlaylists('u2')).toEqual([]);
	});
});
