import { and, eq } from 'drizzle-orm';
import type { Db } from '../db';
import { playlists, playlistSongs } from '../db/schema';
import { createPlaylist, listUserLibrarySongs, type LibrarySongSummary } from './playlists';
import { computeEvictionScore } from '../eviction/score';

// Below this many songs, an artist grouping reads as noise rather than a
// useful browsing shortcut (a single-song "artist" playlist is just that
// one song, redundant with finding it any other way).
const MIN_SONGS_PER_ARTIST = 2;

// Below this many total library songs, a 3-way percentile split produces
// slices too thin to mean anything (e.g. a 6-song library's "top 20%" is
// one song) — skip generating the play-history playlists entirely rather
// than ship a degenerate result.
const MIN_LIBRARY_SIZE_FOR_RECOMMENDATIONS = 30;

// Caps each generated playlist's size — a library's most-played slice
// could otherwise be hundreds of songs, which reads as "everything", not
// a curated shortlist.
const MAX_SONGS_PER_SMART_PLAYLIST = 50;

async function deleteAutoGeneratedPlaylists(db: Db, userId: string): Promise<void> {
	await db.delete(playlists).where(and(eq(playlists.userId, userId), eq(playlists.kind, 'auto_generated')));
}

async function writeAutoGeneratedPlaylist(db: Db, userId: string, name: string, videoIds: string[]): Promise<void> {
	if (videoIds.length === 0) return;
	const { id } = await createPlaylist(db, { userId, name, kind: 'auto_generated' });
	await db.insert(playlistSongs).values(videoIds.map((videoId, position) => ({ playlistId: id, videoId, position })));
}

function groupByArtist(library: LibrarySongSummary[]): Map<string, LibrarySongSummary[]> {
	const groups = new Map<string, LibrarySongSummary[]>();
	for (const song of library) {
		if (!song.artist) continue;
		const existing = groups.get(song.artist);
		if (existing) existing.push(song);
		else groups.set(song.artist, [song]);
	}
	return groups;
}

/**
 * playCount * 0.5^(daysSinceLastPlayed / halfLife) — same formula as
 * eviction scoring (see computeEvictionScore), reused here for the
 * opposite purpose: ranking a library from "most listened to recently" to
 * "never played", rather than "safest to delete".
 */
function scoreSong(song: LibrarySongSummary, now: Date): number {
	return computeEvictionScore({
		playCount: song.playCount,
		lastPlayedAt: song.lastPlayedAt ? new Date(song.lastPlayedAt) : null,
		now
	});
}

/**
 * Wipes and regenerates every kind='auto_generated' playlist for one
 * user — Artists groupings and three play-history-based playlists. Always
 * a full replace, never an incremental update: these playlists are
 * read-only (see assertPlaylistMutable in playlists.ts) and rebuilt from
 * scratch on every scheduled run (see the CI workflow that calls
 * generateSmartPlaylistsForAllUsers), so there's no "diff against last
 * time" state worth preserving.
 */
export async function generateSmartPlaylistsForUser(db: Db, userId: string): Promise<void> {
	await deleteAutoGeneratedPlaylists(db, userId);

	const library = await listUserLibrarySongs(db, userId);
	if (library.length < MIN_LIBRARY_SIZE_FOR_RECOMMENDATIONS) return;

	for (const [artist, songs] of groupByArtist(library)) {
		if (songs.length < MIN_SONGS_PER_ARTIST) continue;
		// Stable, deterministic order independent of any particular run's
		// iteration order — title is what a listener actually recognizes an
		// artist playlist's track order by, unlike e.g. raw import order.
		const ordered = [...songs].sort((a, b) => a.title.localeCompare(b.title));
		await writeAutoGeneratedPlaylist(db, userId, artist, ordered.slice(0, MAX_SONGS_PER_SMART_PLAYLIST).map((s) => s.videoId));
	}

	const now = new Date();
	const scored = library
		.map((song) => ({ song, score: scoreSong(song, now) }))
		.sort((a, b) => b.score - a.score);

	const topCount = Math.round(scored.length * 0.2);
	const bottomCount = Math.round(scored.length * 0.2);
	const mostPlayed = scored.slice(0, topCount);
	const rediscover = scored.slice(topCount, scored.length - bottomCount);
	// The bottom slice is sorted by score ascending (least-listened first)
	// rather than kept in the descending order used above — there's no
	// meaningful "top" within a slice of mostly-tied, near-zero scores, so
	// this ordering at least surfaces the very-longest-untouched songs
	// first instead of an arbitrary one.
	const neverPlayed = scored.slice(scored.length - bottomCount).sort((a, b) => a.score - b.score);

	await writeAutoGeneratedPlaylist(
		db,
		userId,
		'Most Played',
		mostPlayed.slice(0, MAX_SONGS_PER_SMART_PLAYLIST).map((s) => s.song.videoId)
	);
	await writeAutoGeneratedPlaylist(
		db,
		userId,
		'Rediscover',
		rediscover.slice(0, MAX_SONGS_PER_SMART_PLAYLIST).map((s) => s.song.videoId)
	);
	await writeAutoGeneratedPlaylist(
		db,
		userId,
		'Never Played',
		neverPlayed.slice(0, MAX_SONGS_PER_SMART_PLAYLIST).map((s) => s.song.videoId)
	);
}

export async function generateSmartPlaylistsForAllUsers(db: Db): Promise<{ processedUsers: number }> {
	const allUsers = await db.query.users.findMany({ columns: { id: true } });
	for (const user of allUsers) {
		await generateSmartPlaylistsForUser(db, user.id);
	}
	return { processedUsers: allUsers.length };
}
