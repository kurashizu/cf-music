import type { Db } from '../db';
import { playlists, playlistSongs } from '../db/schema';
import { createPlaylist, listUserLibrarySongs, type LibrarySongSummary } from './playlists';
import { computeEvictionScore } from '../../shared/eviction-score';
import { getVectorsByVideoIds } from '../embedding/similarity';
import { cosineSimilarity } from '../embedding/vector-codec';
import { chunk } from '../../shared/chunk';

// Below this many songs, an artist grouping reads as noise rather than a
// useful browsing shortcut (a single-song "artist" playlist is just that
// one song, redundant with finding it any other way).
const MIN_SONGS_PER_ARTIST = 2;

// Below this many total library songs, every percentile/cluster-based
// playlist below produces slices too thin to mean anything (e.g. a 6-song
// library's "top 20%" is one song) — skip generating all of them rather
// than ship a degenerate result. Artist groupings aren't gated by this,
// only the play-history and embedding-based playlists are.
const MIN_LIBRARY_SIZE_FOR_RECOMMENDATIONS = 30;

// Caps an artist grouping's size — an artist with hundreds of songs in the
// library would otherwise produce a playlist that reads as "everything",
// not a curated shortlist. The play-history/embedding playlists don't have
// this cap: they're each already a bounded slice of the library by
// construction (a percentile split, or a single cluster), so their size is
// meant to scale with the library instead of being clipped independently.
const MAX_SONGS_PER_ARTIST_PLAYLIST = 50;

// D1's ~100-bound-parameter cap (see findKnownVideoIds in import/jobs.ts
// for the same limit) — this insert binds 3 params per row (playlistId,
// videoId, position; addedAt has a DB default), so 30 rows stays safely
// under it.
const PLAYLIST_SONGS_INSERT_BATCH_SIZE = 30;

// Fixed names for the 6 non-artist smart playlists — exported so callers
// (the library page's load function, the sidebar) can tell them apart from
// the artist-named groupings without guessing, since both kinds share the
// same `kind: 'auto_generated'` value and only differ by name.
export const RECENTLY_PLAYED_NAME = 'Recently Played';
export const ON_REPEAT_NAME = 'On Repeat';
export const FORGOTTEN_FAVORITES_NAME = 'Forgotten Favorites';
export const THIS_WEEKS_VIBE_NAME = "This Week's Vibe";
export const DEEP_CUTS_NAME = 'Deep Cuts';
export const SOUND_CLUSTERS_NAME = 'Sound Clusters';

export const SMART_PLAYLIST_NAMES = [
	RECENTLY_PLAYED_NAME,
	ON_REPEAT_NAME,
	FORGOTTEN_FAVORITES_NAME,
	THIS_WEEKS_VIBE_NAME,
	DEEP_CUTS_NAME,
	SOUND_CLUSTERS_NAME
] as const;

const RECENT_WINDOW_DAYS = 7;
const FORGOTTEN_WINDOW_DAYS = 30;

// Each of the 3 play-history/embedding playlists caps out at this many
// songs — unlike the percentile-based cut of the old 3-playlist design,
// several of these (On Repeat, Deep Cuts, the cluster pick) don't have a
// size that's naturally bounded by the library's own proportions, so this
// keeps them readable as a curated shortlist rather than "the whole
// library, re-sorted".
const MAX_SONGS_PER_SMART_PLAYLIST = 100;

async function deleteAutoGeneratedPlaylists(db: Db, userId: string): Promise<void> {
	await db
		.delete(playlists)
		.where(and(eq(playlists.userId, userId), eq(playlists.kind, 'auto_generated')));
}

async function writeAutoGeneratedPlaylist(
	db: Db,
	userId: string,
	name: string,
	videoIds: string[]
): Promise<void> {
	if (videoIds.length === 0) return;
	const { id } = await createPlaylist(db, { userId, name, kind: 'auto_generated' });
	const rows = videoIds.map((videoId, position) => ({ playlistId: id, videoId, position }));
	for (const batch of chunk(rows, PLAYLIST_SONGS_INSERT_BATCH_SIZE)) {
		await db.insert(playlistSongs).values(batch);
	}
}

function groupByArtist(library: LibrarySongSummary[]): Map<string, LibrarySongSummary[]> {
	const groups = new Map<string, LibrarySongSummary[]>();
	for (const song of library) {
		if (!song.artist) continue;
		const existing = groups.get(song.artist);
		if (existing) existing.push(song);
		else groups.set(song.artist, [song]);
	}
	return groups;
}

async function generateArtistPlaylists(
	db: Db,
	userId: string,
	library: LibrarySongSummary[]
): Promise<void> {
	for (const [artist, songs] of groupByArtist(library)) {
		if (songs.length < MIN_SONGS_PER_ARTIST) continue;
		// Stable, deterministic order independent of any particular run's
		// iteration order — title is what a listener actually recognizes an
		// artist playlist's track order by, unlike e.g. raw import order.
		const ordered = [...songs].sort((a, b) => a.title.localeCompare(b.title));
		await writeAutoGeneratedPlaylist(
			db,
			userId,
			artist,
			ordered.slice(0, MAX_SONGS_PER_ARTIST_PLAYLIST).map((s) => s.videoId)
		);
	}
}

function daysSince(dateString: string, now: Date): number {
	return (now.getTime() - new Date(dateString).getTime()) / (1000 * 60 * 60 * 24);
}

function median(values: number[]): number {
	if (values.length === 0) return 0;
	const sorted = [...values].sort((a, b) => a - b);
	const mid = Math.floor(sorted.length / 2);
	return sorted.length % 2 === 0 ? (sorted[mid - 1] + sorted[mid]) / 2 : sorted[mid];
}

/**
 * The 3 pure play-history playlists — no embeddings, just playCount/
 * lastPlayedAt from userSongs (already joined into `library` by
 * listUserLibrarySongs). Each is an independent time-window/threshold
 * filter rather than a slice of one continuous score, so they don't
 * overlap by construction: "played in the last 7 days" vs "played 30+
 * days ago" are mutually exclusive windows, and On Repeat is a straight
 * playCount ranking that ignores recency entirely.
 */
async function generatePlayHistoryPlaylists(
	db: Db,
	userId: string,
	library: LibrarySongSummary[],
	now: Date
): Promise<void> {
	const played = library.filter((s) => s.lastPlayedAt !== null);

	const recentlyPlayed = played
		.filter((s) => daysSince(s.lastPlayedAt!, now) <= RECENT_WINDOW_DAYS)
		.sort((a, b) => new Date(b.lastPlayedAt!).getTime() - new Date(a.lastPlayedAt!).getTime());

	const onRepeat = [...library]
		.sort((a, b) => b.playCount - a.playCount)
		.filter((s) => s.playCount > 0);

	// "Used to like it" needs some minimum play count, not just "played
	// once, ages ago" — the played-songs' own median playCount scales that
	// threshold to this specific library instead of a fixed number that'd
	// be meaningless for a light listener vs. a heavy one.
	const playCountThreshold = median(played.map((s) => s.playCount));
	const forgottenFavorites = played
		.filter(
			(s) =>
				daysSince(s.lastPlayedAt!, now) >= FORGOTTEN_WINDOW_DAYS &&
				s.playCount >= playCountThreshold
		)
		.sort((a, b) => daysSince(b.lastPlayedAt!, now) - daysSince(a.lastPlayedAt!, now));

	await writeAutoGeneratedPlaylist(
		db,
		userId,
		RECENTLY_PLAYED_NAME,
		recentlyPlayed.slice(0, MAX_SONGS_PER_SMART_PLAYLIST).map((s) => s.videoId)
	);
	await writeAutoGeneratedPlaylist(
		db,
		userId,
		ON_REPEAT_NAME,
		onRepeat.slice(0, MAX_SONGS_PER_SMART_PLAYLIST).map((s) => s.videoId)
	);
	await writeAutoGeneratedPlaylist(
		db,
		userId,
		FORGOTTEN_FAVORITES_NAME,
		forgottenFavorites.slice(0, MAX_SONGS_PER_SMART_PLAYLIST).map((s) => s.videoId)
	);
}

/**
 * Weighted-average embedding of the songs played in the last
 * RECENT_WINDOW_DAYS, weighted by playCount — a stand-in for "how this
 * user's taste is currently leaning", not a single song's vector. Returns
 * null if nothing was played that recently or none of those songs have an
 * embedding yet, in which case the two playlists derived from it are
 * skipped for this run (see generateEmbeddingPlaylists).
 */
function computeThisWeeksVibeVector(
	library: LibrarySongSummary[],
	vectors: Map<string, Float32Array>,
	now: Date
): Float32Array | null {
	const recentlyPlayed = library.filter(
		(s) => s.lastPlayedAt !== null && daysSince(s.lastPlayedAt!, now) <= RECENT_WINDOW_DAYS
	);
	if (recentlyPlayed.length === 0) return null;
	// vectors covers the whole library, not just recentlyPlayed — checked
	// per-song below rather than on vectors.size, since a library that has
	// *some* embeddings doesn't guarantee any of them are for songs played
	// in this window.
	if (!recentlyPlayed.some((s) => vectors.has(s.videoId))) return null;

	const dimensions = vectors.values().next().value!.length;
	const sum = new Float32Array(dimensions);
	let totalWeight = 0;
	for (const song of recentlyPlayed) {
		const vector = vectors.get(song.videoId);
		if (!vector) continue;
		// A song played zero times in the window can't happen (recentlyPlayed
		// is already filtered to lastPlayedAt within the window), but a song
		// with playCount 0 and a non-null lastPlayedAt is defensively treated
		// as weight 1, not 0 — otherwise it'd silently vanish from the
		// average instead of contributing at all.
		const weight = Math.max(song.playCount, 1);
		for (let i = 0; i < dimensions; i++) sum[i] += vector[i] * weight;
		totalWeight += weight;
	}
	if (totalWeight === 0) return null;
	for (let i = 0; i < dimensions; i++) sum[i] /= totalWeight;
	return sum;
}

/**
 * This Week's Vibe (closest to the current taste vector) and Deep Cuts
 * (farthest from it) — both derived from the same vector so they're
 * genuinely opposite ends of one axis, not two independently-tuned
 * queries. Requires embeddings, so silently produces neither playlist if
 * computeThisWeeksVibeVector can't build one (nothing played recently, or
 * no embeddings exist yet for what was played) — see its own comment.
 */
async function generateEmbeddingPlaylists(
	db: Db,
	userId: string,
	library: LibrarySongSummary[],
	vectors: Map<string, Float32Array>,
	now: Date
): Promise<void> {
	const vibeVector = computeThisWeeksVibeVector(library, vectors, now);
	if (!vibeVector) return;

	const scored = library
		.map((song) => {
			const vector = vectors.get(song.videoId);
			return vector ? { song, similarity: cosineSimilarity(vibeVector, vector) } : null;
		})
		.filter((s) => s !== null);
	if (scored.length === 0) return;

	const thisWeeksVibe = [...scored].sort((a, b) => b.similarity - a.similarity);
	const deepCuts = [...scored].sort((a, b) => a.similarity - b.similarity);

	await writeAutoGeneratedPlaylist(
		db,
		userId,
		THIS_WEEKS_VIBE_NAME,
		thisWeeksVibe.slice(0, MAX_SONGS_PER_SMART_PLAYLIST).map((s) => s.song.videoId)
	);
	await writeAutoGeneratedPlaylist(
		db,
		userId,
		DEEP_CUTS_NAME,
		deepCuts.slice(0, MAX_SONGS_PER_SMART_PLAYLIST).map((s) => s.song.videoId)
	);
}

// k = sqrt(librarySize / 2), clamped — enough clusters to be meaningful for
// a large library without fragmenting a smaller one into single-song
// "clusters". Bounds chosen so even the MIN_LIBRARY_SIZE_FOR_RECOMMENDATIONS
// floor (30 songs) gets a sensible k (~4), and a huge library doesn't spin
// up more clusters than this playlist's own size cap could ever show
// meaningfully.
const MIN_CLUSTERS = 3;
const MAX_CLUSTERS = 10;
const KMEANS_MAX_ITERATIONS = 20;

function pickClusterCount(librarySize: number): number {
	return Math.min(MAX_CLUSTERS, Math.max(MIN_CLUSTERS, Math.round(Math.sqrt(librarySize / 2))));
}

// A simple string hash of the user id seeds a deterministic PRNG for
// k-means' initial centroids — reruns of the same library on the same day
// land on the same clusters instead of reshuffling randomly every 6 hours,
// while still varying centroid placement across different users.
function seededRandom(seed: string): () => number {
	let state = 0;
	for (const char of seed) state = (state * 31 + char.charCodeAt(0)) >>> 0;
	return () => {
		state = (state * 1664525 + 1013904223) >>> 0;
		return state / 0xffffffff;
	};
}

function euclideanDistanceSquared(a: Float32Array, b: Float32Array): number {
	let sum = 0;
	for (let i = 0; i < a.length; i++) {
		const diff = a[i] - b[i];
		sum += diff * diff;
	}
	return sum;
}

/**
 * Standard k-means (Lloyd's algorithm) over a library's own embeddings —
 * scoped to one user's songs only, never across users. Runs to
 * KMEANS_MAX_ITERATIONS or until no point changes cluster, whichever comes
 * first; there's no early-exit tolerance check beyond that since this only
 * needs "a reasonable grouping", not a precisely converged one.
 */
function kMeans(vectors: Map<string, Float32Array>, k: number, seed: string): Map<string, number> {
	const videoIds = [...vectors.keys()];
	const random = seededRandom(seed);

	// Randomly assign each point one of k labels first, then derive initial
	// centroids from those groups (rather than picking k raw points as
	// centroids directly) — guarantees every cluster starts with at least
	// one member, avoiding a degenerate empty-cluster centroid at iteration 0.
	let assignments = new Map(videoIds.map((id) => [id, Math.floor(random() * k)]));

	for (let iteration = 0; iteration < KMEANS_MAX_ITERATIONS; iteration++) {
		const dimensions = vectors.get(videoIds[0])!.length;
		const centroids: Float32Array[] = Array.from({ length: k }, () => new Float32Array(dimensions));
		const counts = new Array(k).fill(0);
		for (const videoId of videoIds) {
			const cluster = assignments.get(videoId)!;
			const vector = vectors.get(videoId)!;
			for (let i = 0; i < dimensions; i++) centroids[cluster][i] += vector[i];
			counts[cluster]++;
		}
		for (let c = 0; c < k; c++) {
			if (counts[c] === 0) continue;
			for (let i = 0; i < dimensions; i++) centroids[c][i] /= counts[c];
		}

		let changed = false;
		const nextAssignments = new Map<string, number>();
		for (const videoId of videoIds) {
			const vector = vectors.get(videoId)!;
			let bestCluster = 0;
			let bestDistance = Infinity;
			for (let c = 0; c < k; c++) {
				if (counts[c] === 0) continue;
				const distance = euclideanDistanceSquared(vector, centroids[c]);
				if (distance < bestDistance) {
					bestDistance = distance;
					bestCluster = c;
				}
			}
			nextAssignments.set(videoId, bestCluster);
			if (assignments.get(videoId) !== bestCluster) changed = true;
		}
		assignments = nextAssignments;
		if (!changed) break;
	}

	return assignments;
}

/**
 * Picks the single largest sound cluster in the user's library (via
 * k-means over their embeddings) as one more angle on "songs that go
 * together" — distinct from This Week's Vibe, which is anchored to recent
 * plays specifically. Songs already selected for This Week's Vibe are
 * excluded from consideration so the two playlists don't just repeat each
 * other when recent listening happens to dominate the largest cluster too.
 */
async function generateSoundClustersPlaylist(
	db: Db,
	userId: string,
	library: LibrarySongSummary[],
	allVectors: Map<string, Float32Array>,
	excludeVideoIds: Set<string>
): Promise<void> {
	const candidates = library.filter((s) => !excludeVideoIds.has(s.videoId));
	const vectors = new Map(
		candidates
			.map((s) => [s.videoId, allVectors.get(s.videoId)])
			.filter((entry): entry is [string, Float32Array] => entry[1] !== undefined)
	);
	if (vectors.size < MIN_CLUSTERS) return;

	const k = pickClusterCount(vectors.size);
	const assignments = kMeans(vectors, k, userId);

	const clusterSizes = new Map<number, number>();
	for (const cluster of assignments.values()) {
		clusterSizes.set(cluster, (clusterSizes.get(cluster) ?? 0) + 1);
	}
	const largestCluster = [...clusterSizes.entries()].sort((a, b) => b[1] - a[1])[0]?.[0];
	if (largestCluster === undefined) return;

	const videoIds = [...assignments.entries()]
		.filter(([, cluster]) => cluster === largestCluster)
		.map(([videoId]) => videoId);
	await writeAutoGeneratedPlaylist(
		db,
		userId,
		SOUND_CLUSTERS_NAME,
		videoIds.slice(0, MAX_SONGS_PER_SMART_PLAYLIST)
	);
}

/**
 * Wipes and regenerates every kind='auto_generated' playlist for one user
 * — artist groupings plus the 6 fixed smart playlists (SMART_PLAYLIST_NAMES).
 * Always a full replace, never an incremental update: these playlists are
 * read-only (see assertPlaylistMutable in playlists.ts) and rebuilt from
 * scratch on every scheduled run (see the CI workflow that calls
 * generateSmartPlaylistsForAllUsers), so there's no "diff against last
 * time" state worth preserving.
 */
export async function generateSmartPlaylistsForUser(db: Db, userId: string): Promise<void> {
	await deleteAutoGeneratedPlaylists(db, userId);

	const library = await listUserLibrarySongs(db, userId);
	await generateArtistPlaylists(db, userId, library);

	if (library.length < MIN_LIBRARY_SIZE_FOR_RECOMMENDATIONS) return;

	const now = new Date();
	await generatePlayHistoryPlaylists(db, userId, library, now);

	// Fetched once and shared across every embedding-based generator below —
	// they all draw from largely overlapping subsets of the same library, so
	// re-querying song_embeddings per generator was pure read amplification.
	const vectors = await getVectorsByVideoIds(
		db,
		library.map((s) => s.videoId)
	);
	await generateEmbeddingPlaylists(db, userId, library, vectors, now);

	// This Week's Vibe already picked its own top slice above, but the
	// exclusion set for Sound Clusters is "everything played recently
	// enough to have fed the vibe vector", not just what made the capped
	// top slice — otherwise near-duplicates of already-surfaced recent
	// songs could still dominate the largest cluster.
	const recentlyPlayedIds = new Set(
		library
			.filter(
				(s) => s.lastPlayedAt !== null && daysSince(s.lastPlayedAt!, now) <= RECENT_WINDOW_DAYS
			)
			.map((s) => s.videoId)
	);
	await generateSoundClustersPlaylist(db, userId, library, vectors, recentlyPlayedIds);
}

export async function generateSmartPlaylistsForAllUsers(
	db: Db
): Promise<{ processedUsers: number }> {
	const allUsers = await db.query.users.findMany({ columns: { id: true } });
	for (const user of allUsers) {
		await generateSmartPlaylistsForUser(db, user.id);
	}
	return { processedUsers: allUsers.length };
}
